-- F6 无状态会话：JWT 双令牌。服务端只保留两份轻量状态：
-- 1) 刷新令牌台账：一次性使用，刷新即 ACTIVE→USED 并换新；登出置 REVOKED；过期登记定时清理。
-- 2) 访问令牌黑名单：登出的 access 按 jti 登记到自然过期，过滤链命中即拒；过期登记定时清理。
-- 两张表都不存令牌原文，令牌中也不含密码等敏感明文。
CREATE TABLE IF NOT EXISTS t_refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti VARCHAR(64) NOT NULL,
    username VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    replaced_by_jti VARCHAR(64),
    create_time TIMESTAMP,
    used_time TIMESTAMP,
    revoke_time TIMESTAMP,
    CONSTRAINT uk_refresh_token_jti UNIQUE (jti)
);
CREATE INDEX IF NOT EXISTS idx_refresh_token_status ON t_refresh_token (status);
CREATE INDEX IF NOT EXISTS idx_refresh_token_expires ON t_refresh_token (expires_at);

CREATE TABLE IF NOT EXISTS t_token_blacklist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti VARCHAR(64) NOT NULL,
    username VARCHAR(64) NOT NULL,
    token_type VARCHAR(16) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    reason VARCHAR(32) NOT NULL DEFAULT 'LOGOUT',
    create_time TIMESTAMP,
    CONSTRAINT uk_token_blacklist_jti UNIQUE (jti)
);
CREATE INDEX IF NOT EXISTS idx_token_blacklist_expires ON t_token_blacklist (expires_at);

