-- 结算单头：按期间把已完工未结算的作业单一次汇总成单，结算依据直接落库，不再导出二次加工。
-- active_tag 为有效占位标记：进行中恒为 ACTIVE；作废后改为 CANCELLED-<id>，
-- 配合 uk_settlement_period_active 保证同一期间最多一张有效结算单，作废释放期间可重新生成。
CREATE TABLE IF NOT EXISTS t_settlement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_no VARCHAR(40) NOT NULL,
    period VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    order_count INT NOT NULL DEFAULT 0,
    total_area DECIMAL(14, 2) NOT NULL DEFAULT 0,
    unit_price DECIMAL(12, 2) NOT NULL,
    total_amount DECIMAL(14, 2) NOT NULL DEFAULT 0,
    active_tag VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_settlement_no UNIQUE (settlement_no),
    CONSTRAINT uk_settlement_period_active UNIQUE (period, active_tag)
);

-- 结算单明细：生成时快照作业单（单号/农机/作业类型/轨迹面积/单价/金额），
-- uk_settlement_item_order_active 保证一张作业单最多进入一张有效结算单，作废后释放可重新结算。
CREATE TABLE IF NOT EXISTS t_settlement_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    order_no VARCHAR(40) NOT NULL,
    machine_id BIGINT,
    operation_type VARCHAR(40),
    track_area DECIMAL(12, 2) NOT NULL,
    unit_price DECIMAL(12, 2) NOT NULL,
    amount DECIMAL(14, 2) NOT NULL,
    active_tag VARCHAR(24) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT,
    create_time TIMESTAMP,
    CONSTRAINT uk_settlement_item_order_active UNIQUE (order_id, active_tag)
);
CREATE INDEX IF NOT EXISTS idx_settlement_item_header ON t_settlement_item (settlement_id);

-- 结算单状态流转日志：每次变更带变更前后版本与操作人，只追加、不修改，流转历史完整可查。
CREATE TABLE IF NOT EXISTS t_settlement_status_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id BIGINT NOT NULL,
    settlement_no VARCHAR(40) NOT NULL,
    from_status VARCHAR(16),
    to_status VARCHAR(16) NOT NULL,
    from_version INT,
    to_version INT,
    operator VARCHAR(64) NOT NULL,
    request_no VARCHAR(64),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_settlement_log_header ON t_settlement_status_log (settlement_id);

-- 结算状态机迁移规则（配置化）：所有流转以此表为准，enabled=0 即停用该迁移，在线调整即时生效。
CREATE TABLE IF NOT EXISTS t_settlement_transition (
