-- F7 农机预约排班防撞：新预约先查时段重叠（首尾相接不算冲突），相邻 18 分钟缓冲内不许插单；
-- 提交后先 HELD 临时锁定，只保留 35 分钟，未确认自动 EXPIRED 释放，确认后转 CONFIRMED 长期占用；
-- 取消立即 CANCELLED 释放、时段可再约。口径新旧双策略：booking.mode=NEW/LEGACY/PARALLEL，
-- 异常可一键切回 LEGACY（旧手工台账口径：仅严格时间重叠才拦）。
-- buffer_minutes/lock_ttl_minutes 在预约时快照当时口径，便于追溯。
CREATE TABLE IF NOT EXISTS t_machine_appointment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_no VARCHAR(40) NOT NULL,
    machine_id BIGINT NOT NULL,
    plot_name VARCHAR(80),
    operator_code VARCHAR(64) NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'HELD',
    lock_deadline TIMESTAMP,
    buffer_minutes INT NOT NULL DEFAULT 18,
    lock_ttl_minutes INT NOT NULL DEFAULT 35,
    cancel_reason VARCHAR(255),
    request_no VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    version INT NOT NULL DEFAULT 0,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_machine_appointment_no UNIQUE (appointment_no),
    CONSTRAINT uk_machine_appointment_request UNIQUE (request_no)
);
CREATE INDEX IF NOT EXISTS idx_appt_machine_time ON t_machine_appointment (machine_id, start_time, end_time);
CREATE INDEX IF NOT EXISTS idx_appt_status ON t_machine_appointment (status, lock_deadline);

-- 预约状态流转日志：HELD→CONFIRMED / HELD→EXPIRED（自动过期）/ HELD|CONFIRMED→CANCELLED，只追加不修改。
CREATE TABLE IF NOT EXISTS t_machine_appointment_log (
